// Writes one version of one of the two bun-apps (see ../README.md):
//
//   node gen.mjs <plain|mixed|lazy> <1.0.0|1.1.0> <out-dir>
//
// The three apps have the same six ES modules, a local CommonJS
// dependency and the real npm package ms@2.1.3:
//
//   plain — every module imported statically: Bun writes NO lazy-init
//           module at all;
//   mixed — two of the six (archive, codec) reached only through require()
//           from a CommonJS module (loader.cjs): Bun wraps exactly those
//           two in lazy inits, the other four stay eager;
//   lazy  — all six reached only through loader.cjs, and the entry only
//           calls it: every module lazy, a two-statement entry — the
//           shape the module markers describe (Claude Code's).
//   chunks — built with `--compile --splitting --format esm` (Claude Code's
//           layout from 2.1.242): units and palette imported statically,
//           the other four loaded through `import()`, each its own chunk;
//           the four lazy modules share a helper module (a shared chunk).
//   assets — the chunks app plus a fifth lazy module, notes, that imports
//           three TEXT files (`with { type: "text" }`) and one `file`
//           asset — the embedded files Claude Code carries from 2.1.246
//           (exp217; built with Bun 1.4.1, ../../bun-chunk-assets).
//   order — a different, smaller code-split app (exp218; Bun 1.4.1,
//           ../../bun-chunk-order) whose entry loads everything through
//           import() and requires nothing, so Bun's runtime chunk (its
//           interop helpers) is itself loaded lazily: alpha default-imports
//           a Node built-in and a CommonJS dependency, beta imports a
//           dependency that ships pre-bundled (its own CommonJS helper
//           declared in one `var` with values that read `Object`, its
//           wrapped modules in a later statement). The two shapes a linker
//           must order exactly as ESM evaluates them.
//
// Deterministic: same arguments, same bytes.
import * as fs from "node:fs";
import * as path from "node:path";

const [app, version, out] = process.argv.slice(2);
if (!["plain", "mixed", "lazy", "chunks", "assets", "order"].includes(app) || !["1.0.0", "1.1.0"].includes(version) || !out) {
  console.error("usage: node gen.mjs <plain|mixed|lazy|chunks|assets|order> <1.0.0|1.1.0> <out-dir>");
  process.exit(2);
}
const v2 = version === "1.1.0";

// Module name, report tag, seed. Each module is a chain of small functions
// that reference each other and their own table only — no module reads
// another, so the reference graph has a clean seam at every module edge.
const MODULES = [
  ["units", "UNITS", 3],
  ["palette", "PALETTE", 5],
  ["archive", "ARCHIVE", 7],
  ["codec", "CODEC", 11],
  ["ledger", "LEDGER", 13],
  ["router", "ROUTER", 17]
];
const STEPS = 40;
const LAZY = new Set(
  {
    plain: [],
    mixed: ["archive", "codec"],
    lazy: MODULES.map(([name]) => name),
    chunks: ["archive", "codec", "ledger", "router"],
    assets: ["archive", "codec", "ledger", "router"]
  }[app]
);
// The chunks app's lazy modules import a shared helper (its own chunk).
const CHUNKED = app === "chunks" || app === "assets";
const SHARED = CHUNKED;

function moduleSource(name, tag, seed) {
  const table = `${tag}_TABLE`;
  const shared = SHARED && LAZY.has(name);
  const lines = [
    `// ${name}.js — generated by gen.mjs (${app} app, v${version})`,
    ...(shared ? ['import { mix } from "./shared.js";'] : []),
    `const ${table} = [];`,
    "for (let i = 0; i < 8; i++) {",
    shared ? `  ${table}.push(mix(i, ${seed}));` : `  ${table}.push((i * ${seed} + 3) % 17);`,
    "}",
    "",
    `export function ${name}Step0(x) {`,
    `  return (x * ${seed} + ${table}[x % 8]) % 101;`,
    "}"
  ];
  for (let k = 1; k < STEPS; k++) {
    const prev = `${name}Step${k - 1}`;
    const back = `${name}Step${Math.max(0, k - 2)}`;
    lines.push(
      `export function ${name}Step${k}(x) {`,
      `  return (${prev}(x) + ${back}(x + ${k}) * ${(k % 5) + 1}) % 1009;`,
      "}"
    );
  }
  // v1.1.0: palette and archive change their report (a real code change
  // in an eager and in a lazy module).
  const changed = v2 && (name === "palette" || name === "archive");
  lines.push(
    `export function ${name}Report(n) {`,
    changed
      ? `  return "${tag}#" + String(${name}Step${STEPS - 1}(n)).padStart(4, "0");`
      : `  return "${tag}#" + ${name}Step${STEPS - 1}(n);`,
    "}",
    ""
  );
  return lines.join("\n");
}

const CLOCK = `"use strict";
// A local CommonJS dependency (vendor extraction).
var origin = 1000;
function tick(n) {
  return origin + n * 60;
}
${v2 ? "function tock(n) {\n  return origin - n;\n}\n" : ""}
module.exports = { tick${v2 ? ", tock" : ""} };
`;

// A CommonJS module that requires the lazy ES modules: each only
// initializes on its first call, so Bun wraps each in a lazy init.
function loaderSource() {
  const lines = ["// loader.cjs — generated by gen.mjs: requires its modules lazily."];
  for (const name of LAZY) {
    lines.push(
      `function ${name}Report(n) {`,
      `  const { ${name}Report: report } = require("./${name}.js");`,
      "  return report(n);",
      "}"
    );
  }
  lines.push("", `module.exports = { ${[...LAZY].map((n) => `${n}Report`).join(", ")} };`, "");
  return lines.join("\n");
}

// The lazy app's entry only calls the loader: its whole report runs in
// the loader's caller, and the bundle's eager tail is two statements.
function lazyMainSource() {
  return [
    `// main.js — generated by gen.mjs (${app} app, v${version})`,
    'import loader from "./loader.cjs";',
    'import { report } from "./report.cjs";',
    "",
    "report(loader);",
    ""
  ].join("\n");
}

const REPORT = `// report.cjs — generated by gen.mjs: prints the lazy app's report.
const ms = require("ms");
const clock = require("./vendor/clock.cjs");
function report(loader) {
  const lines = [
${MODULES.map(([name]) => `    \`${name}: \${loader.${name}Report(${name.length})}\`,`).join("\n")}
    \`ms: \${ms(90000)} \${ms("2h")}\`,
    \`clock: \${clock.tick(3)}\`
  ];
  for (const line of lines) {
    console.log(line);
  }
}
module.exports = { report };
`;

const SHARED_SOURCE = `// shared.js — generated by gen.mjs: the lazy modules' common helper.
export const SALT = [3, 1, 4, 1, 5, 9, 2, 6];
export function mix(i, seed) {
  return (i * seed + SALT[i % 8]) % 17;
}
`;

// The assets app's notes module: three text imports (UTF-16 when not
// ASCII, Bun's storage) and a `file` import whose path it reads.
// v1.1.0 changes the intro (a new content-hash name).
const NOTES = `// notes.js — generated by gen.mjs: reads its embedded files.
import { readFileSync } from "node:fs";
import intro from "./notes/intro.md" with { type: "text" };
import rules from "./notes/rules.txt" with { type: "text" };
import page from "./notes/page.html" with { type: "text" };
import blobPath from "./notes/blob.bin" with { type: "file" };

export function notesReport() {
  const blob = readFileSync(blobPath).toString("hex");
  return ["NOTES#" + JSON.stringify(intro), JSON.stringify(rules), JSON.stringify(page), "blob " + blob].join(" | ");
}
`;
const NOTES_FILES = {
  "intro.md": `# Notes \u2014 caf\u00e9 \u{1f600}\n\n${v2 ? "Second edition.\n" : "First edition.\n"}`,
  "rules.txt": "rule 1: say `hi` and ${not} a template\\n\r\nrule 2: 'quotes' \"too\"\n",
  "page.html": '<p class="x">page</p>\n'
};
const NOTES_BLOB = Buffer.from([0, 1, 2, 250, 255]);

// The chunks app's entry: two modules static, four through import().
function chunksMainSource() {
  const eager = MODULES.filter(([name]) => !LAZY.has(name));
  return [
    `// main.js — generated by gen.mjs (${app} app, v${version})`,
    ...eager.map(([name]) => `import { ${name}Report } from "./${name}.js";`),
    'import ms from "ms";',
    'import clock from "./vendor/clock.cjs";',
    "",
    "async function main() {",
    "  const lines = [",
    ...eager.map(([name]) => `    \`${name}: \${${name}Report(${name.length})}\`,`),
    "  ];",
    ...[...LAZY].map(
      (name) =>
        `  const { ${name}Report } = await import("./${name}.js");\n  lines.push(\`${name}: \${${name}Report(${name.length})}\`);`
    ),
    ...(app === "assets"
      ? ['  const { notesReport } = await import("./notes.js");', "  lines.push(`notes: ${notesReport()}`);"]
      : []),
    "  lines.push(`ms: ${ms(90000)} ${ms(\"2h\")}`, `clock: ${clock.tick(3)}`);",
    "  for (const line of lines) {",
    "    console.log(line);",
    "  }",
    "}",
    "main();",
    ""
  ].join("\n");
}

function mainSource() {
  if (app === "lazy") return lazyMainSource();
  if (CHUNKED) return chunksMainSource();
  const imports = [];
  const reports = [];
  for (const [name] of MODULES) {
    if (LAZY.has(name)) continue;
    imports.push(`import { ${name}Report } from "./${name}.js";`);
    reports.push(`  \`${name}: \${${name}Report(${name.length})}\`,`);
    // The loader comes right after palette: units and palette are emitted
    // BEFORE the lazy modules, ledger and router after them.
    if (name === "palette" && LAZY.size > 0) {
      imports.push('import loader from "./loader.cjs";');
      for (const lazy of LAZY) {
        reports.push(`  \`${lazy}: \${loader.${lazy}Report(${lazy.length})}\`,`);
      }
    }
  }
  return [
    `// main.js — generated by gen.mjs (${app} app, v${version})`,
    ...imports,
    'import ms from "ms";',
    'import clock from "./vendor/clock.cjs";',
    "",
    "const lines = [",
    ...reports,
    "  `ms: ${ms(90000)} ${ms(\"2h\")}`,",
    "  `clock: ${clock.tick(3)}`",
    "];",
    "for (const line of lines) {",
    "  console.log(line);",
    "}",
    ""
  ].join("\n");
}

// The order app (exp218): see the header.
const ORDER_MAIN = `// main.js — generated by gen.mjs (order app, v${version})
async function main() {
  const { alphaReport } = await import("./alpha.js");
  console.log(alphaReport(3));
  const { betaReport } = await import("./beta.js");
  console.log(betaReport(4));
}
main();
`;
// A chain of small functions over the module's own table (as
// moduleSource writes), so the linked program has a bundle's worth of
// top-level bindings.
function orderChain(name, seed) {
  const lines = [`const ${name}Table = [];`, "for (let i = 0; i < 8; i++) {", `  ${name}Table.push((i * ${seed} + 3) % 17);`, "}"];
  lines.push(`function ${name}Step0(x) {`, `  return (x * ${seed} + ${name}Table[x % 8]) % 101;`, "}");
  for (let k = 1; k < STEPS; k++) {
    lines.push(
      `function ${name}Step${k}(x) {`,
      `  return (${name}Step${k - 1}(x) + ${name}Step${Math.max(0, k - 2)}(x + ${k}) * ${(k % 5) + 1}) % 1009;`,
      "}"
    );
  }
  return lines.join("\n");
}
const ORDER_ALPHA = `// alpha.js — generated by gen.mjs: a default import of a Node built-in
// and of a CommonJS module (both read through Bun's __toESM).
import os from "node:os";
import clock from "./vendor/clock.cjs";
${orderChain("alpha", 7)}
export function alphaReport(n) {
  return ${v2 ? '"ALPHA#" + String(clock.tick(n)).padStart(6, "0")' : '"ALPHA#" + clock.tick(n)'} + " " + alphaStep${STEPS - 1}(n) + " " + typeof os.platform;
}
`;
const ORDER_BETA = `// beta.js — generated by gen.mjs
import dial from "./vendor/dial.cjs";
import { sep } from "node:path";
import { prebuiltValue } from "./vendor/prebuilt.js";
${orderChain("beta", 11)}
export function betaReport(n) {
  return "BETA#" + dial.turn(n) + sep + prebuiltValue() + " " + betaStep${STEPS - 1}(n);
}
`;
const ORDER_DIAL = `module.exports = { turn(n) { return n * 7; } };
`;
const ORDER_PREBUILT = `// A dependency that ships pre-bundled: its own CommonJS helper, declared
// in one statement with values that read Object; then (after a function
// declaration, so the statements stay apart) its wrapped modules.
var { create: makeObject, getPrototypeOf: protoOf } = Object, hasOwn = Object.prototype.hasOwnProperty, wrapCommonJS = (cb, mod) => () => (mod || cb((mod = { exports: {} }).exports, mod), mod.exports);
function describe(value) {
  return "value " + value;
}
var requireInner = wrapCommonJS((exports) => {
  exports.value = 42;
});
var requireOuter = wrapCommonJS((exports, module) => {
  module.exports = { inner: requireInner().value };
});
export function prebuiltValue() {
  return describe(requireOuter().inner).length + requireOuter().inner + (hasOwn.call({ a: 1 }, "a") ? 1 : 0) + (protoOf(makeObject(null)) === null ? 1 : 0);
}
`;

const pkg = {
  name: `bun-${app}-fixture`,
  version,
  private: true,
  dependencies: { ms: "2.1.3" }
};

fs.mkdirSync(path.join(out, "src", "vendor"), { recursive: true });
fs.writeFileSync(path.join(out, "package.json"), `${JSON.stringify(pkg, null, 2)}\n`);
if (app === "order") {
  fs.writeFileSync(path.join(out, "src", "main.js"), ORDER_MAIN);
  fs.writeFileSync(path.join(out, "src", "alpha.js"), ORDER_ALPHA);
  fs.writeFileSync(path.join(out, "src", "beta.js"), ORDER_BETA);
  fs.writeFileSync(path.join(out, "src", "vendor", "clock.cjs"), CLOCK);
  fs.writeFileSync(path.join(out, "src", "vendor", "dial.cjs"), ORDER_DIAL);
  fs.writeFileSync(path.join(out, "src", "vendor", "prebuilt.js"), ORDER_PREBUILT);
  process.exit(0);
}
for (const [name, tag, seed] of MODULES) {
  fs.writeFileSync(path.join(out, "src", `${name}.js`), moduleSource(name, tag, seed));
}
fs.writeFileSync(path.join(out, "src", "vendor", "clock.cjs"), CLOCK);
if (LAZY.size > 0 && !CHUNKED) fs.writeFileSync(path.join(out, "src", "loader.cjs"), loaderSource());
if (SHARED) fs.writeFileSync(path.join(out, "src", "shared.js"), SHARED_SOURCE);
if (app === "lazy") fs.writeFileSync(path.join(out, "src", "report.cjs"), REPORT);
fs.writeFileSync(path.join(out, "src", "main.js"), mainSource());
if (app === "assets") {
  fs.writeFileSync(path.join(out, "src", "notes.js"), NOTES);
  fs.mkdirSync(path.join(out, "src", "notes"), { recursive: true });
  for (const [name, text] of Object.entries(NOTES_FILES)) {
    fs.writeFileSync(path.join(out, "src", "notes", name), text);
  }
  fs.writeFileSync(path.join(out, "src", "notes", "blob.bin"), NOTES_BLOB);
}
