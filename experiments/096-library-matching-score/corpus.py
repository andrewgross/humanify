def freeze_cc():
    """`freeze --corpus cc` (exp150): Claude Code 2.1.216 alone, its truth the re-labelled sample (cc_truth). No
    entry has a source map, so every map-derived layer of the corpus is empty (each builder writes its manifest)."""
    manifest = {"schema": "exp096-corpus/1", "corpus": "cc", "frozen": True,
                "note": "exp150 Claude Code corpus: 2.1.216 scored on the seed-95 redraw of exp095's negatives sample, "
                        "re-labelled (labels and truth under /work/cc-library-truth/, never committed)",
                "entries": []}
    entry, files, how = cc_entry()
    d = os.path.join(lib096.DATA, "corpus", entry["id"])
    os.makedirs(d, exist_ok=True)
    src = files["bundle"]
    dst = os.path.join(d, os.path.basename(src))
    if not os.path.exists(dst) or sha256_file(dst) != sha256_file(src):
        shutil.copyfile(src, dst)
    entry["files"] = {"bundle": {"name": os.path.basename(src), "sha256": sha256_file(dst),
                                 "bytes": os.path.getsize(dst), "origin": src}}
    entry["truth"] = {"method": "sample"}
    p = lib096.truth_path(entry)
    write_gz_json(p, cc_truth())
    entry["truth"]["sha256"] = sha256_file(p)
    manifest["entries"].append(entry)
    open(lib096.MANIFEST, "w").write(dump(manifest))
    print(f"froze {len(manifest['entries'])} entry -> {lib096.MANIFEST}")


def build_truth(job):
    entry, files, how = job
    if how[0] == "cc":
        t = cc_truth()
    elif how[0] == "pnpm":
        t = map_truth(files["bundle"], None, pnpm_version, None, (files["innerMap"], 1))
    else:
        t = map_truth(files["bundle"], how[2], install_versions(how[1]), how[1])
    p = lib096.truth_path(entry)
    write_gz_json(p, t)
    return entry["id"], sha256_file(p)


def freeze(jobs):
    manifest = {"schema": "exp096-corpus/1", "entries": []}
    work = []
    for entry, files, how in entries():
        d = os.path.join(lib096.DATA, "corpus", entry["id"])
        os.makedirs(d, exist_ok=True)
        entry["files"] = {}
        for role, src in files.items():
            name = os.path.basename(src)
            dst = os.path.join(d, name)
            if not os.path.exists(dst) or sha256_file(dst) != sha256_file(src):
                shutil.copyfile(src, dst)
            entry["files"][role] = {"name": name, "sha256": sha256_file(dst), "bytes": os.path.getsize(dst),
                                    "origin": src}
        entry["truth"] = {"method": "sample" if how[0] == "cc" else "sourcemap"}
        manifest["entries"].append(entry)
        work.append((entry, files, how))
    with multiprocessing.Pool(jobs) as pool:
        shas = dict(pool.map(build_truth, work, chunksize=1))
    for e in manifest["entries"]:
        e["truth"]["sha256"] = shas[e["id"]]
    open(lib096.MANIFEST, "w").write(dump(manifest))
    print(f"froze {len(manifest['entries'])} entries -> {lib096.MANIFEST}")


def build_origins(entry):
    """The origin layer of one source-mapped entry, aligned to its frozen truth segments (refused if the
    re-decoded segments do not equal the frozen ones byte for byte)."""
    import origins as O
    truth = lib096.load_truth(entry)
    js = lib096.corpus_path(entry, "bundle")
    text = open(js, encoding="utf8").read()
    smap = json.load(open(lib096.corpus_path(entry, "map")))
    if "innerMap" in entry["files"]:
        srcmap = json.load(open(lib096.corpus_path(entry, "innerMap")))
        segs = O.segments(text, smap, (srcmap, 1))
    else:
        srcmap = smap
        segs = O.segments(text, smap)
    if [[s[0], s[1]] for s in segs] != truth["segments"]:
        raise SystemExit(f"REFUSED: {entry['id']}: re-decoded segments differ from the frozen truth")
    shippers = [s[0] for s in truth["sources"]]
    names, kinds, runs = O.origin_runs(segs, O.Origins(srcmap["sources"], srcmap.get("sourcesContent"), shippers))
    p = lib096.origins_path(entry)
    write_gz_json(p, {"schema": O.SCHEMA, "names": names, "kinds": kinds, "runs": runs,
                      "segments": len(segs)})
    return entry["id"], sha256_file(p)


def freeze_origins(jobs):
    import origins as O
    todo = [e for e in lib096.load_manifest()["entries"] if e["truth"]["method"] == "sourcemap"]
    with multiprocessing.Pool(jobs) as pool:
        shas = dict(pool.map(build_origins, todo, chunksize=1))
    open(lib096.ORIGINS_MANIFEST, "w").write(dump({
        "schema": O.SCHEMA, "corpusSha256": lib096.manifest_sha(),
        "entries": {k: shas[k] for k in sorted(shas)}}))
    print(f"froze the origin layer of {len(shas)} entries -> {lib096.ORIGINS_MANIFEST}")


def verify():
    bad = 0
    for e in lib096.load_manifest()["entries"]:
        for role, f in e["files"].items():
            p = lib096.corpus_path(e, role)
            if not os.path.exists(p) or sha256_file(p) != f["sha256"]:
                print("MOVED", e["id"], role, p)
                bad += 1
        if sha256_file(lib096.truth_path(e)) != e["truth"]["sha256"]:
            print("MOVED", e["id"], "truth")
            bad += 1
    om = lib096.load_origins_manifest()
    for e in lib096.load_manifest()["entries"]:
        if e["truth"]["method"] == "sourcemap" and sha256_file(lib096.origins_path(e)) != om["entries"].get(e["id"]):
            print("MOVED", e["id"], "origins")
            bad += 1
    print("corpus OK" if not bad else f"corpus BROKEN: {bad} file(s)")
    return 1 if bad else 0


