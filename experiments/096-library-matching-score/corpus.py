def sources_table(smap_sources, base, app_pkg, version_of):
    import truth as T
    out = []
    for src in smap_sources:
        if src.startswith("\0"):
            # a bundler-generated module with no file (rollup's `\0commonjsHelpers.js`, webpack's runtime, spelled
            # "\0webpack/..." by exp100's webpack recipe): no package wrote it, so it is never judged
            out.append(["<unmapped>", None, src])
            continue
        if re.match(r"^(https?|webpack):", src):
            # a URL (`https://raw.githubusercontent.com/...`, `webpack://pkg/...`): esbuild CHAINS a package's own
            # source map, so this is library code whose package the path cannot say — never app code
            out.append(["<foreign>", None, src])
            continue
        pr = T.package_root(src)
        if pr is None:
            out.append(["<app>", None, None])
            continue
        pkg, root, f = pr
        if app_pkg is not None and pkg == app_pkg:
            out.append(["<self>", None, f])
            continue
        out.append([pkg, version_of(root, pkg), f])
    return out


def install_versions(base):
    cache = {}

    def version_of(root, pkg):
        p = os.path.normpath(os.path.join(base, root, "package.json"))
        if p not in cache:
            try:
                cache[p] = json.load(open(p)).get("version")
            except (OSError, ValueError):
                cache[p] = None
        return cache[p]
    return version_of


def pnpm_version(root, pkg):
    m = re.search(r"\.pnpm/([^/]+)/node_modules/", root)
    if not m:
        return None
    at = m.group(1).replace("+", "/").split("_")[0]
    return at.rsplit("@", 1)[1] if "@" in at[1:] else None


def map_truth(js, app_pkg, version_of, base, inner=None):
    # origins.segments: truth.segments' output exactly, but linear on long non-ASCII lines (truth.py re-encodes the
    # line prefix per mapping: hours on a terser-minified Electron bundle). build_origins re-checks the equality.
    import origins as T
    text = open(js, encoding="utf8").read()
    smap = json.load(open(js + ".map"))
    if inner:
        imap = json.load(open(inner[0]))
        segs = T.segments(text, smap, (imap, inner[1]))
        sources = imap["sources"]
    else:
        segs = T.segments(text, smap)
        sources = smap["sources"]
    return {"schema": "exp096-truth/1", "method": "sourcemap", "appPackage": app_pkg,
            "sources": sources_table(sources, base, app_pkg, version_of),
            "segments": [[s[0], s[1]] for s in segs]}


def cc_truth():
    specs = {}
    spec_file = f"{NEG}/exactlab/specs.txt"  # exp095's exact-build specs: gone with its lane (2026-10-25), optional
    for line in (open(spec_file) if os.path.exists(spec_file) else ()):
        if line.startswith("#") or "|" not in line:
            continue
        for spec in line.split("|")[1].split():
            name, ver = spec.rsplit("@", 1)
            specs.setdefault(name, ver)
    meta = json.load(open(f"{NEG}/data/sample-meta.json"))
    rows = []
    for line in open(f"{NEG}/labels.jsonl"):
        r = json.loads(line)
        if r["stratum"] not in meta["strata"]:
            continue  # the review queue is never used in rates
        lab = r["label"]
        row = {"s": r["start"], "e": r["end"], "b": r["bytes"], "stratum": r["stratum"],
               "label": lab.split(":", 1)[1] if lab.startswith("library:") else "<" + lab + ">"}
        if lab.startswith("library:"):
            row.update(pkg=r["pkg"], version=r.get("version_if_known") or specs.get(r["pkg"]))
        rows.append(row)
    rows.sort(key=lambda r: r["s"])
    return {"schema": "exp096-truth/1", "method": "sample", "strata": meta["strata"], "seed": meta["seed"],
            "populationUnits": meta["populationUnits"], "populationBytes": meta["populationBytes"], "rows": rows}


