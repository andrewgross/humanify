"""exp096: the FIXED corpus — freeze it (copy every input under <DATA>/corpus/<id>/, build its ground truth under
<DATA>/truth/, write corpus.json with every sha256) and verify it.

usage: <venv python> -I corpus.py freeze [--jobs N]      (once; rewrites corpus.json)
       <venv python> -I corpus.py freeze --corpus cc       (exp150: Claude Code alone, the re-labelled sample)
       <venv python> -I corpus.py origins [--jobs N] [--corpus dev|test]   (the origin layer; rewrites origins.json
                                                         or origins-test.json, see origins.py)
       <venv python> -I corpus.py verify [--corpus dev|test]   (every file's sha256 against the manifest + origins)
The `test` corpus (exp100's frozen test split, corpus-test.json) is frozen by experiments/100-test-split/scripts/
freeze_test.py; `freeze` here builds the dev corpus only.

The inputs are NOT committed (Claude Code is not ours to publish; the held-out bundles are large) — corpus.json
records where each came from and its sha256, and the runner refuses a corpus file whose hash moved.

Ground truth per statement unit (labelled at score time, against whatever units the run's binary reports):
  sourcemap   every generated byte -> the source it maps to (exp095 misses truth.py `segments`, same decoder);
              a unit's label is the package holding the MAJORITY of its mapped bytes (score_claims.py's labeller):
              `node_modules/<pkg>` = that package, the app's own package = <self>, a URL source = <foreign>
              (esbuild chains a package's own map: library code of unknown package — neither app nor library in
              any rate), anything else = <app>.
              Version = the package.json beside the mapped file in the app's install (held-out, esbuild app), or
              the pnpm path (wrangler). Recorded per source at freeze time, so the installs may go away.
  origins     (origins.py, a separate frozen layer: <DATA>/truth/<id>.origins.json.gz, shas in origins.json) per
              mapped byte, the ORIGIN package when the shipping package carries a vendored / pre-bundled copy of
              another package (a vendored directory in the path, or a bundler module marker in the shipped file).
              Read from the frozen map's sources and sourcesContent only. Source-mapped entries only.
  sample      Claude Code 2.1.216: the exp095 negatives lane's 620-statement stratified random sample (labels.jsonl
              strata S0-S3, seed 95; blind second pass 124/124), with its strata sizes for the ratio estimator.
              Since exp150 (`freeze --corpus cc`) read from NEG = /work/cc-library-truth/2.1.216: the seed-95 redraw,
              re-labelled after exp095's lane was deleted (experiments/150-bun-testbed/README.md).
"""
