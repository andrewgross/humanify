"""Scorer 4's truth corrections (exp104 truth audit), one object per corpus entry. Two of the three changes live
here; the third (families) is families_lib.py.

  carried  The truth credits every generated byte to the LAST mapping before it (truth.py `segments`: a segment
           runs to the next one). A unit with no mapping of its own is credited to whatever mapping preceded it,
           which is wrong whenever the bundler simply emitted none for the code: Bun maps no JSON module
           (lighthouse's 13 MB of locale tables were credited to a 978-byte @paulirish/trace_engine file) and
           maps get-east-asian-width's lookup tables to ora's index.js. Rule: a statement unit with NO mapping
           segment starting inside it, whose identifier-like / numeric tokens (TOKEN, only tokens some map
           source contains, at least MIN_TOKENS of them) are mostly ABSENT from the source it was carried from
           (share present < CARRIED_SHARE), is `<unmapped>`: the map does not say where it came from. Read only
           from the frozen bundle, map and truth: no index, no claims.
  copies   A vendored copy that origins.py cannot see (no marker, no vendored directory): the frozen COPIES layer
           (experiments/104-truth-audit/copies.py: code match + the shipper's own npm manifest declaring the
           origin + the shipped file naming it), as byte ranges. A unit takes the copy's origin when most of its
           bytes lie in one origin's ranges under the unit's own shipper, and origins.py gave it none.
"""
import bisect
import collections
import gzip
import json
import os
import re

import lib096
from lib096 import sha256_file

TOKEN = re.compile(r"[A-Za-z_$][\w$]{3,}|\d{3,}")
MIN_TOKENS = 3
CARRIED_SHARE = 0.5


def copies_manifest_path():
    """copies.json (dev) or copies-test.json (test): read at call time, after lib096.use()."""
    return lib096.CORPORA[lib096.CORPUS]["copies"]


def load_copies_manifest():
    with open(copies_manifest_path()) as fh:
        return json.load(fh)


def copies_sha():
    return lib096.sha256_bytes(lib096.dump(load_copies_manifest()).encode())


def load_copies(entry, cm):
    p = os.path.join(lib096.DATA, "truth", entry["id"] + ".copies.json.gz")
    got = sha256_file(p)
    if got != cm["entries"].get(entry["id"]):
        raise SystemExit(f"REFUSED: copies {p} sha256 {got[:12]} != copies.json")
    with gzip.open(p, "rt") as fh:
        return json.load(fh)["ranges"]


class Audit:
    def __init__(self, entry, truth, cm):
        self.offs = [s[0] for s in truth["segments"]]
        self.segs = truth["segments"]
        with open(lib096.corpus_path(entry, "bundle"), "rb") as fh:
            self.text = fh.read()
        mp = lib096.corpus_path(entry, "innerMap" if "innerMap" in entry["files"] else "map")
        with open(mp) as fh:
            contents = json.load(fh).get("sourcesContent") or []
        self.tok = {si: set(TOKEN.findall(c)) for si, c in enumerate(contents) if c}
        self.all = set().union(*self.tok.values()) if self.tok else set()
        ranges = sorted(load_copies(entry, cm))
        self.copy_at = [r[0] for r in ranges]
        self.copies = ranges

    def carried(self, s, e):
        """True when the unit [s, e) has no mapping of its own and its tokens are mostly absent from the source
        the previous mapping names."""
        k0 = bisect.bisect_left(self.offs, s)
        if k0 == 0 or bisect.bisect_left(self.offs, e) > k0:
            return False
        si = self.segs[k0 - 1][1]
        if si not in self.tok:
            return False
        t = set(TOKEN.findall(self.text[s:e].decode("utf8", "replace"))) & self.all
        if len(t) < MIN_TOKENS:
            return False
        return len(t & self.tok[si]) < CARRIED_SHARE * len(t)

    def copy_origin(self, s, e, shipper):
        """(origin, declaring dependency) when most of [s, e) lies in one origin's copy ranges of this shipper."""
        k = max(bisect.bisect_right(self.copy_at, s) - 1, 0)
        by = collections.Counter()
        while k < len(self.copies) and self.copies[k][0] < e:
            a, b, ship, origin, dep = self.copies[k][:5]
            ov = min(b, e) - max(a, s)
            if ov > 0 and ship == shipper:
                by[(origin, dep)] += ov
            k += 1
        if not by:
            return None
        (best, n), = sorted(by.items(), key=lambda kv: (-kv[1], kv[0]))[:1]
        return best if 2 * n > e - s else None


# ---------------------------------------------------------------- scorer 6 (exp107): the decoder

# Each rule can be switched off: both off reproduces scorer 4's segments (and so its cards) exactly
# (experiments/107-zero-app-claims/verify_decoder.py).
RULES6 = {"utf16": True, "unmapped": True}


def redecode(entry, truth, origins):
    """(truth, origins) with the segments re-decoded under scorer 6's decoder rules (decoder.py: UTF-16 generated
    columns; one-field segments kept as unmapped). Copies; the frozen files are never rewritten. A segment that
    maps to nothing points at one extra source row, `<unmapped>`. The origin layer is indexed by scorer 4's
    segments, which are exactly the re-decoded segments that map somewhere, in the same order (checked: refused
    otherwise), so each keeps its origin and an unmapped segment has none."""
    if truth["method"] != "sourcemap" or not (RULES6["utf16"] or RULES6["unmapped"]):
        return truth, origins
    import decoder
    with open(lib096.corpus_path(entry, "bundle"), encoding="utf8", newline=None if not RULES6["utf16"] else "") \
            as fh:
        text = fh.read()
    with open(lib096.corpus_path(entry, "map")) as fh:
        smap = json.load(fh)
    inner = None
    if "innerMap" in entry["files"]:
        with open(lib096.corpus_path(entry, "innerMap")) as fh:
            inner = (json.load(fh), 1)
    segs = decoder.segments(text, smap, inner, utf16=RULES6["utf16"], unmapped=RULES6["unmapped"])
    old = truth["segments"]
    mapped = [s for s in segs if s[1] is not None]
    if len(mapped) != len(old) or any(a[1] != b[1] for a, b in zip(mapped, old)):
        raise SystemExit(f"REFUSED: {entry['id']}: the re-decoded mapped segments are not scorer 4's, in order")
    none = len(truth["sources"])
    new_segs = [[s[0], none if s[1] is None else s[1]] for s in segs]
    new_truth = {**truth, "segments": new_segs, "sources": [*truth["sources"], ["<unmapped>", None, None]]}
    if origins is None:
        return new_truth, None
    # per old segment index -> its run's (name, kind); re-run-length over the new segment list
    run_at = [r[0] for r in origins["runs"]]
    runs, prev, k = [], None, 0
    for j, s in enumerate(segs):
        if s[1] is None:
            o = (-1, -1)
        else:
            r = origins["runs"][bisect.bisect_right(run_at, k) - 1] if run_at else [0, -1, -1]
            o = (r[1], r[2])
            k += 1
        if o != prev:
            runs.append([j, o[0], o[1]])
            prev = o
    return new_truth, {**origins, "runs": runs, "segments": len(new_segs)}
