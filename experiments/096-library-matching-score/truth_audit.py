VIRTUAL = re.compile(r"\?commonjs-[a-z-]+$")


def patch_sources(entry, truth, chm):
    """The truth with scorer 5's source-table corrections (a copy; the frozen truth is never rewritten):

      virtual  a source whose id ends in a rollup CommonJS-plugin query (`entry.cjs?commonjs-entry`,
               `?commonjs-proxy`, `?commonjs-module`, `?commonjs-exports`, ...) is bundler-generated glue: no package
               and no app author wrote it, so it is `<unmapped>` (like corpus.sources_table's `\\0` rule).
      chained  a source the truth called `<app>` that a bundler reached through an installed package's OWN source
               map (the path does not exist and that package's map lists it: experiments/106-matcher-hygiene/
               scorer5/chained.py, frozen per entry) keeps that package.
    """
    if truth["method"] != "sourcemap":
        return truth
    srcs = [list(r) for r in truth["sources"]]
    if RULES5["virtual"]:
        mp = lib096.corpus_path(entry, "innerMap" if "innerMap" in entry["files"] else "map")
        with open(mp) as fh:
            names = json.load(fh)["sources"]
        for i, n in enumerate(names):
            if i < len(srcs) and isinstance(n, str) and VIRTUAL.search(n):
                srcs[i] = ["<unmapped>", None, n]
    if RULES5["chained"]:
        for i, row in load_chained(entry, chm).items():
            if srcs[i][0] == "<app>":
                srcs[i] = list(row)
    if RULES9["npmchain"]:
        for i, row in load_chained9(entry).items():
            if srcs[i][0] == row[3]:
                srcs[i] = list(row[:3])
    if RULES11["notinstalled"]:
        for i, row in load_chained11(entry).items():
            if srcs[i][0] == row[3]:
                srcs[i] = list(row[:3])
    return {**truth, "sources": srcs}


